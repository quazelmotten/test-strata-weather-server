#[test]
fn streaming_writer_output_is_byte_identical_to_golden() {
    let dir = "/tmp/opencode/wxpt-golden-a".to_string();
    let _c = std::fs::create_dir_all(&dir);
    let hdr = golden_hdr();
    // pairs FIRST, then borrow the planes out of them for the slice API
    let mut pairs: Vec<(f64, Vec<f32>)> = Vec::<(f64, Vec<f32>)>::new();
    for (li, lv) in LEVEL_VALS.iter().enumerate() {
        pairs.push((*lv, plane_vals(li)));
    }
    let refs: Vec<&[f32]> = [&pairs[0].1[..], &pairs[1].1[..], &pairs[2].1[..]].to_vec();

    // (1) the historical wrapper (unchanged signature) ...
    let p_wrap = format!("{0}/wrap.bin", dir);
    let w1 = write_bin_atomic(p_wrap.to_string(), &hdr, &refs);
    assert!(w1.is_ok());
    // (2) ... and the new streaming entry point over a borrowed source.
    let p_stream = format!("{0}/stream.bin", dir);
    let w2 = write_bin_atomic_stream(p_stream.to_string(), &hdr, pairs.len(),
                                     PairPlanes { items: &pairs, idx: 0 });
    assert!(w2.is_ok());
    // (3) the retained whole-buffer reference implementation.
    let p_ref = format!("{0}/ref.bin", dir);
    ref_write_whole_buffer(&p_ref, &hdr, &refs);

    let want = unhex(&golden_hex());
    assert!(want.len() == 488);
    let got_wrap = read_bytes(&p_wrap);
    let got_stream = read_bytes(&p_stream);
    let got_ref = read_bytes(&p_ref);
    assert!(got_wrap == want);
    assert!(got_stream == want);
    assert!(got_ref == want);

    // (4) the committed v2 fixture agrees with the embedded hex (guards against
    // a silently modified fixture).
    let fx = "../../tests/fixtures/writer_golden_v2.bin".to_string();
    let got_fx = read_bytes(&fx);
    assert!(got_fx == want);

    // (4b) V1.4 phase C: the sealed slot agrees with the CRATE's own digest over
    // the same region, so the Python generator, this file's independent
    // `crc32_ref`, the reference serializer and `wx_core::storage` all describe
    // ONE integrity function. The slot is also pinned non-zero: zero is the
    // "no CRC present" legacy sentinel, which a sealed writer must never emit
    // (`crc_slot_value` maps a raw digest of 0 onto 1).
    let head_end = BIN_FIXED_HEADER + hdr.levels.len() * 4;
    let want_slot = crc_slot_value(header_crc(&want[0 .. head_end]));
    let got_slot = (got_fx[BIN_CRC_OFFSET] as u32)
                 | ((got_fx[BIN_CRC_OFFSET + 1] as u32) << 8)
                 | ((got_fx[BIN_CRC_OFFSET + 2] as u32) << 16)
                 | ((got_fx[BIN_CRC_OFFSET + 3] as u32) << 24);
    assert!(got_slot == want_slot);
    assert!(got_slot != 0);

    // (5) the bytes decode back to EXACTLY the input header, statistical
    // metadata included (the accumulation window is what the guard reads).
    let op = open_field(p_stream.to_string());
    match op {
        Err(_e) => { panic!();}
        Ok(mf) => {
            assert!(mf.header.nx == 7 && mf.header.ny == 5);
            assert!(mf.header.scan_ns && !mf.header.winds_grid);
            assert!(mf.header.levels.len() == 3);
            assert!(mf.header.stat.processed);
            assert!(mf.header.stat.kind == STAT_ACCUMULATION);
            assert!(mf.header.stat.begin_secs == 0);
            assert!(mf.header.stat.end_secs == 21600);
            assert!(mf.header.stat.step_secs == 0);
            assert!(mf.header.stat.guards_time());
            // value round-trip untouched by the header growth
            assert!(mf.value(2, 4, 6) == 2046.0);
        }
    }
}

#[test]
fn v1_golden_is_rejected_as_an_old_format_not_misparsed() {
    // V1.3 E0 COMPAT CHOICE (docs/DECISIONS.md): an old field file CANNOT carry
    // the statistical metadata, so it must never answer a query. The reader says
    // BAD VERSION loudly; `pipeline::ingest_run_dir` turns that into the same
    // storage-format recovery the grid.bin upgrade trap uses. This test pins the
    // reader half of that contract against the retained v1 artifact.
    let dir = "/tmp/opencode/wxpt-golden-v1reject".to_string();
    let _c = std::fs::create_dir_all(&dir);
    let fx = "../../tests/fixtures/writer_golden_v1.bin".to_string();
    let v1 = read_bytes(&fx);
    assert!(v1.len() == 456); // 24-byte fixed header + 3 levels + 3*35 planes
    let dst = format!("{0}/legacy.bin", dir);
    write_raw(&dst, &v1[..]);

    // version field says 1 while this build writes 2
    let ver = bin_version_of_path(dst.as_str());
    match ver {
        None => { panic!(); }
        Some(vv) => {
            assert!(vv == 1);
            assert!(vv != BIN_VERSION);
        }
    }
    // decode_header refuses instead of inventing stat metadata
    let dec = decode_header(&v1[..]);
    match dec {
        Ok(_) => { panic!(); }
        Err(e) => {
            match e {
                wx_core::storage::HeaderError::BadVersion => {}
                _ => { panic!(); }
            }
        }
    }
    // and open_field reports the DISTINCT string the warm-start recovery keys on
    let of = open_field(dst.to_string());
    match of {
        Ok(_) => { panic!();}
        Err(msg) => { assert!(msg == "bad bin version"); }
    }
}

#[test]
fn streaming_writer_chunks_across_the_buffer_boundary_identically() {
    // A plane LARGER than WRITE_CHUNK_BYTES forces MANY internal flushes: nx*ny*4
    // = 700*600*4 = 1.68 MB > 256 KiB. The old writer materialized this whole
    // file at once; the new one must still produce the SAME BYTES.
    let dir = "/tmp/opencode/wxpt-golden-b".to_string();
    let _c = std::fs::create_dir_all(&dir);
    let hdr = BinHeader {
        nx: 700,
        ny: 600,
        levels: [1000.0, 925.0].to_vec(),
        scan_ns: true,
        winds_grid: false,
        stat: StatMeta::instantaneous(),
    };
    let mut pa: Vec<f32> = Vec::<f32>::new();
    let mut pb: Vec<f32> = Vec::<f32>::new();
    for j in 0 .. 600 {
        for i in 0 .. 700 {
            // values chosen so mantissa rounding cannot hide a byte-order bug
            pa.push(((j * 700 + i) % 100003) as f32);
            pb.push(-((j * 7919 + i) % 99991) as f32);
        }
    }
    let refs: Vec<&[f32]> = [&pa[..], &pb[..]].to_vec();
    let p_new = format!("{0}/big.bin", dir);
    let w = write_bin_atomic(p_new.to_string(), &hdr, &refs);
    assert!(w.is_ok());
    let p_old = format!("{0}/big_ref.bin", dir);
    ref_write_whole_buffer(&p_old, &hdr, &refs);
    let a = read_bytes(&p_new);
    let b = read_bytes(&p_old);
    assert!(a.len() == b.len());
    let mut same = true;
    for k in 0 .. a.len() {
        if a[k] != b[k] {
            same = false;
            break;
        }
    }
    assert!(same);
    assert!(a.len() == BIN_FIXED_HEADER + 2 * 4 + 2 * 700 * 600 * 4);
}
