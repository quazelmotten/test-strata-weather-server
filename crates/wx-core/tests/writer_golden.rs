/// Raw bytes of a file on disk (mmap copy).
fn read_bytes(path: &str) -> Vec<u8> {
    let f = File::open(path);
    match f {
        Err(_) => { [].to_vec()}
        Ok(h) => {
            let m = unsafe { Mmap::map(&h) };
            match m {
                Err(_) => { [].to_vec()}
                Ok(region) => {
                    let mut out: Vec<u8> = Vec::<u8>::new();
                    for k in 0 .. region.len() {
                        out.push(region[k]);
                    }
                    out
                }
            }
        }
    }
}

fn write_raw(path: &str, bytes: &[u8]) {
    let d = File::create(path);
    match d {
        Err(_) => { panic!();}
        Ok(mut h) => {
            let _w = h.write_all(bytes);
        }
    }
}

/// RETAINED reference implementation of the writer SHAPE: build the ENTIRE file
/// as one Vec<u8> (header + every plane, little-endian f32) and `write_all` it —
/// the V1.1 algorithm (`write_bin_atomic` before phase A). The HEADER BYTES are
/// hand-serialized here, independent of `wx_core::storage::encode_header`, so
/// the equivalence proof covers the algorithm AND an outside reading of the
/// documented layout (the same layout `scripts/gen_writer_golden.py` emits).
fn ref_write_whole_buffer(path: &str, hdr: &BinHeader, planes: &[&[f32]]) {
    let mut bytes: Vec<u8> = Vec::<u8>::new();
    // magic | version | nx | ny | nlevels | flags | kind | processed | 3 reserved
    for b in [0x57u8, 0x58, 0x50, 0x54, 0x42, 0x49, 0x4E, 0x31] {
        bytes.push(b);
    }
    push_u32(&mut bytes, BIN_VERSION);
    push_u32(&mut bytes, hdr.nx);
    push_u32(&mut bytes, hdr.ny);
    push_u16(&mut bytes, hdr.levels.len() as u16);
    let flags: u8 = (if hdr.scan_ns { 1 } else { 0 }) | (if hdr.winds_grid { 2 } else { 0 });
    bytes.push(flags);
    bytes.push(hdr.stat.kind);
    bytes.push(if hdr.stat.processed { 1 } else { 0 });
    bytes.push(0);
    bytes.push(0);
    bytes.push(0);
    // begin / end / step i64 LE
    push_i64(&mut bytes, hdr.stat.begin_secs);
    push_i64(&mut bytes, hdr.stat.end_secs);
    push_i64(&mut bytes, hdr.stat.step_secs);
    assert!(bytes.len() == BIN_CRC_OFFSET); // integrity slot starts right here
    // V1.4 phase C: the level coords are serialized FIRST because the integrity
    // word covers `[0, 52)` plus the coords; the digest is then sealed into the
    // slot and only afterwards do the coords follow on disk. `crc32_ref` below
    // is this file's OWN table-driven implementation (not a call into wx-core),
    // so the gate still catches a wrong digest inside `encode_header`.
    let mut lv: Vec<u8> = Vec::<u8>::new();
    for l in &hdr.levels {
        push_u32(&mut lv, l.to_bits());
    }
    let mut region: Vec<u8> = Vec::<u8>::new();
    region.extend_from_slice(&bytes[0 .. BIN_CRC_OFFSET]);
    region.extend_from_slice(&lv);
    let raw = crc32_ref(&region);
    push_u32(&mut bytes, if raw == 0 { 1 } else { raw });
    bytes.extend_from_slice(&lv);
    for pl in planes.iter() {
        for v in pl.iter() {
            let bits = v.to_bits();
            bytes.push((bits & 0xFF) as u8);
            bytes.push(((bits >> 8) & 0xFF) as u8);
            bytes.push(((bits >> 16) & 0xFF) as u8);
            bytes.push(((bits >> 24) & 0xFF) as u8);
        }
    }
    assert!(bytes.len() == BIN_FIXED_HEADER + hdr.levels.len() * 4 + planes.len() * (hdr.nx as usize) * (hdr.ny as usize) * 4);
    write_raw(path, &bytes);
}

fn push_u32(out: &mut Vec<u8>, v: u32) {
    out.push((v & 0xFF) as u8);
    out.push(((v >> 8) & 0xFF) as u8);
    out.push(((v >> 16) & 0xFF) as u8);
    out.push(((v >> 24) & 0xFF) as u8);
}

fn push_u16(out: &mut Vec<u8>, v: u16) {
    out.push((v & 0xFF) as u8);
    out.push(((v >> 8) & 0xFF) as u8);
}

fn push_i64(out: &mut Vec<u8>, v: i64) {
    let b = v as u64;
    for k in 0 .. 8 {
        out.push(((b >> (k * 8)) & 0xFF) as u8);
    }
}

/// THIS FILE'S OWN reflected CRC-32 (IEEE / zlib polynomial), intentionally
/// duplicated instead of calling `wx_core::storage`: the golden gate must still
/// compare the writer against an INDEPENDENT digest. Four independent
/// implementations then have to agree byte-for-byte: Python's `zlib.crc32`
/// (which produced the committed fixture), this one, the reference serializer
/// above, and `wx_core::storage::header_crc` (pinned below, and again against
/// `zlib_rs::crc32` in wx-ingest's `header_crc_parity.rs`).
fn crc32_ref(data: &[u8]) -> u32 {
    let table = crc32_ref_table();
    let mut crc: u32 = 0xFFFF_FFFF;
    let mut k = 0usize;
    while k < data.len() {
        let idx = ((crc ^ (data[k] as u32)) & 0xFF) as usize;
        crc = table[idx] ^ (crc >> 8);
        k += 1;
    }
    crc ^ 0xFFFF_FFFF
}

fn crc32_ref_table() -> [u32; 256] {
    let mut t: [u32; 256] = [0u32; 256];
    let mut i = 0usize;
    while i < 256 {
        let mut c = i as u32;
        let mut bit = 0usize;
        while bit < 8 {
            let odd = (c & 1) != 0;
            c >>= 1;
            if odd {
                c ^= 0xEDB8_8320;
            }
            bit += 1;
        }
        t[i] = c;
        i += 1;
    }
    t
}

/// Borrowed plane source over (level, plane) pairs — the shape wx-ingest merges
/// into, used here to exercise the generic streaming entry point directly.
struct PairPlanes<'a> {
    pub items: &'a Vec<(f64, Vec<f32>)>,
    pub idx: usize
}

impl<'a> PlaneSource for PairPlanes<'a> {
    fn next_plane(&mut self) -> Option<&[f32]> {
        if self.idx >= self.items.len() {
            return None;
        }
        let r = &self.items[self.idx].1[..];
        self.idx += 1;
        Some(r)
    }
}

