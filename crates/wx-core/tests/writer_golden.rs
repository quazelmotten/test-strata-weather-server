fn unhex(hx: &str) -> Vec<u8> {
    let b = hx.as_bytes().to_vec();
    let mut out: Vec<u8> = Vec::<u8>::new();
    for k in 0 .. b.len() / 2 {
        out.push((nib(b[2 * k]) << 4) | nib(b[2 * k + 1]));
    }
    out
}

fn nib(c: u8) -> u8 {
    if c >= 97 {
        return c - 97 + 10;
    }
    c - 48
}

