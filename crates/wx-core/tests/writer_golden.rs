// V1.2 phase A gate #1 (+ V1.3 phase E0 update): the STREAMING atomic writer must
// be BIT-IDENTICAL to the pre-change whole-buffer writer AND to an INDEPENDENT
// serialization of the documented format.
//
// OLD vs NEW (V1.3 phase E0 bumped BIN_VERSION 1 -> 2):
//   * v1 fixed header = 24 bytes: magic | version | nx | ny | nlevels | flags |
//     ONE reserved byte, then the level coords. Golden artifact:
//     `tests/fixtures/writer_golden_v1.bin` (456 B), captured from the V1.1
//     writer and reproduced by `scripts/gen_writer_golden.py`. KEPT because the
//     current reader must REJECT it (`HeaderError::BadVersion`) rather than
//     mis-parse metadata it never contained — see
//     `v1_golden_is_rejected_as_an_old_format_not_misparsed`.
//   * v2 fixed header = 56 bytes: the same first 23 bytes, then stat_kind (u8),
//     stat_processed (u8), 3 reserved zero bytes, begin/end/step i64 LE (seconds
//     relative to the run time), the header CRC-32 slot (V1.4 phase C: what used
//     to be the trailing RESERVED u32 — same byte count, so the artifact stays
//     488 B and BIN_VERSION stays 2), then the level coords at offset 56. Golden
//     artifact: `tests/fixtures/writer_golden_v2.bin` (488 B = 456 + 32),
//     regenerated by the same script. The golden input carries a REAL
//     0-6 h ACCUMULATION window so the i64 fields are pinned non-zero.
//
// V1.4 phase C CONTRACT CHANGE (justified): the four bytes at 52..56 went from
// "reserved, must be zero" to a CRC-32 integrity word, so BOTH the committed
// fixture and the embedded hex moved by exactly those four bytes (byte-for-byte
// equivalence of wrapper/streaming/reference output is still pinned, and the
// reference implementation below seals independently, so an error in
// `encode_header` still fails the gate). Detection did NOT regress: a foreign
// or rotted value there is still refused, now as `HeaderError::BadCrc` naming
// the class instead of `BadStat`. What a pre-phase-C store (zeros here) means
// to the CURRENT reader is "valid but unsealed", counted by
// `wx_core::storage::crc_counters_snapshot().legacy` — see the module docs and
// `header_integrity.rs` for that compatibility half.
//
// The expected bytes are ALSO embedded below as hex so the test cannot silently
// pass against a mutated fixture, and the retained reference implementation
// serializes the WHOLE file by hand (independent of `encode_header`), so FOUR
// things are compared byte-for-byte: committed fixture, embedded hex, wrapper
// output, streaming output, reference-impl output.

